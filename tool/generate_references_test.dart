// Regenerates the reference data embedded in the SDK:
//   fvm flutter test tool/generate_references_test.dart
//
// * lib/src/ocr/ocrb_glyphs.g.dart: OCR-B glyph templates rendered from
//   tool/fonts/ocrb10.otf at several sizes and blur levels.
// * lib/src/verification/paraguay_front_references.g.dart: grayscale crops of
//   the fixed header ("REPUBLICA DEL PARAGUAY", coat of arms) of both designs:
//   the current one from its public specimen, the previous one from a
//   header-only strip (test/fixtures/paraguay_id_legacy_front_header.png).
import 'dart:convert';
import 'dart:io';
import 'dart:ui' as ui;

import 'package:flutter/painting.dart';
import 'package:flutter/services.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:id_document_scanner/src/ocr/glyph_features.dart';
import 'package:id_document_scanner/src/ocr/gray_image.dart';
import 'package:id_document_scanner/src/verification/header_reference_regions.dart';
import 'package:image/image.dart' as img;

const alphabet = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ<';

/// (font size, blur radius) of each rendering, to cover real print sizes.
const variants = [(28.0, 0), (40.0, 1), (64.0, 2), (40.0, 0)];

Future<GrayImage> render(String character, double fontSize, int blur) async {
  final recorder = ui.PictureRecorder();
  final canvas = Canvas(recorder);
  final size = (fontSize * 2).round();
  canvas.drawRect(Rect.fromLTWH(0, 0, size.toDouble(), size.toDouble()), Paint()..color = const Color(0xFFFFFFFF));
  final painter = TextPainter(
    text: TextSpan(
      text: character,
      style: TextStyle(fontFamily: 'OCRB', fontSize: fontSize, color: const Color(0xFF000000)),
    ),
    textDirection: TextDirection.ltr,
  )..layout();
  painter.paint(canvas, Offset(fontSize * 0.4, fontSize * 0.3));
  final image = await recorder.endRecording().toImage(size, size);
  final bytes = (await image.toByteData(format: ui.ImageByteFormat.rawRgba))!.buffer.asUint8List();
  var rendered = img.Image.fromBytes(width: size, height: size, bytes: bytes.buffer, numChannels: 4);
  if (blur > 0) rendered = img.gaussianBlur(rendered, radius: blur);
  return GrayImage.fromImage(rendered);
}

void main() {
  testWidgets('generate references', (tester) async {
    await tester.runAsync(() async {
      final loader = FontLoader('OCRB')
        ..addFont(Future.value(ByteData.sublistView(File('tool/fonts/ocrb10.otf').readAsBytesSync())));
      await loader.load();

      final entries = <String>[];
      for (final (fontSize, blur) in variants) {
        final capRaster = GlyphFeatures.rasterize(await render('H', fontSize, blur), threshold: 128)!;
        final capHeight = capRaster.$3.toDouble();
        for (final character in alphabet.split('')) {
          final (values, inkWidth, inkHeight) = GlyphFeatures.rasterize(
            await render(character, fontSize, blur),
            threshold: 128,
          )!;
          final bytes = Uint8List.fromList(values.map((v) => (v * 255).round()).toList());
          entries.add(
            "  ('$character', '${base64Encode(bytes)}', "
            '${(inkHeight / capHeight).toStringAsFixed(3)}, ${(inkWidth / inkHeight).toStringAsFixed(3)}),',
          );
        }
      }
      File('lib/src/ocr/ocrb_glyphs.g.dart').writeAsStringSync(
        '// Generated by tool/generate_references_test.dart. Do not edit.\n'
        '// Rendered from the OCR-B outline font (free license, see tool/fonts/OCRB_LICENSE.txt).\n\n'
        '/// (character, ink raster base64, height ratio, aspect) per rendering.\n'
        'const List<(String, String, double, double)> ocrbGlyphTemplates = [\n${entries.join('\n')}\n];\n',
      );

      String references(GrayImage card, List<Rect> regions) => regions
          .map((region) {
            final crop = card.cropNormalized(region);
            return "  (${crop.width}, ${crop.height}, '${base64Encode(crop.pixels)}'),";
          })
          .join('\n');

      final current = GrayImage.fromImage(
        img.decodeWebP(File('test/fixtures/paraguay_id_current_specimen.webp').readAsBytesSync())!,
      ).resize(HeaderReferenceRegions.cardWidth, HeaderReferenceRegions.cardHeight);

      // The legacy reference is only the header strip (no personal data):
      // place it on an empty card so regions keep card coordinates.
      final strip = img.decodePng(File('test/fixtures/paraguay_id_legacy_front_header.png').readAsBytesSync())!;
      final legacyCard = img.Image(width: HeaderReferenceRegions.cardWidth, height: HeaderReferenceRegions.cardHeight);
      img.fill(legacyCard, color: img.ColorRgb8(255, 255, 255));
      img.compositeImage(
        legacyCard,
        img.copyResize(
          strip,
          width: HeaderReferenceRegions.cardWidth,
          height: (HeaderReferenceRegions.cardHeight * HeaderReferenceRegions.legacyHeaderHeight).round(),
        ),
      );
      final legacy = GrayImage.fromImage(legacyCard);

      File('lib/src/verification/paraguay_front_references.g.dart').writeAsStringSync(
        '// Generated by tool/generate_references_test.dart. Do not edit.\n'
        '// Grayscale crops of the fixed card header at HeaderReferenceRegions.cardWidth,\n'
        '// in HeaderReferenceRegions order.\n\n'
        '/// Current design, from the public specimen: (width, height, pixels base64).\n'
        'const List<(int, int, String)> paraguayCurrentFrontReferences = [\n'
        '${references(current, HeaderReferenceRegions.paraguayCurrentFront)}\n];\n\n'
        '/// Previous design, from a header-only strip: (width, height, pixels base64).\n'
        'const List<(int, int, String)> paraguayLegacyFrontReferences = [\n'
        '${references(legacy, HeaderReferenceRegions.paraguayLegacyFront)}\n];\n',
      );
    });
  });
}
